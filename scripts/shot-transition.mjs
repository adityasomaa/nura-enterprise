import { existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import puppeteer from "puppeteer-core";
const BASE = process.env.AUDIT_URL;
const OUT = process.env.SHOT_DIR;
const args = ["--no-sandbox", ...(process.env.HOST_RESOLVER_RULES ? [`--host-resolver-rules=${process.env.HOST_RESOLVER_RULES}`] : [])];
const chrome = [process.env.CHROME_PATH, path.join(process.env.LOCALAPPDATA ?? "", "Google/Chrome/Application/chrome.exe")].find(p => p && existsSync(p));
mkdirSync(OUT, { recursive: true });
const b = await puppeteer.launch({ executablePath: chrome, headless: "new", args });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(BASE + "/id", { waitUntil: "domcontentloaded" });
await new Promise(r => setTimeout(r, 700));
await p.screenshot({ path: path.join(OUT, "t1-loader-awal.png") });
await new Promise(r => setTimeout(r, 1400));
await p.screenshot({ path: path.join(OUT, "t2-loader-membuka.png") });
await new Promise(r => setTimeout(r, 1600));
await p.evaluate(() => { const l=[...document.querySelectorAll("nav a")].find(a=>(a.getAttribute("href")||"").endsWith("/galeri")); l?.click(); });
await new Promise(r => setTimeout(r, 300));
await p.screenshot({ path: path.join(OUT, "t3-tirai-menutup.png") });
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: path.join(OUT, "t4-tirai-membuka.png") });
await new Promise(r => setTimeout(r, 1400));
await p.screenshot({ path: path.join(OUT, "t5-galeri-siap.png") });
console.log("ok");
await b.close();
